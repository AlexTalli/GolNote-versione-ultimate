-- PLAYERS
drop policy if exists players_select_mister_or_same_team_player on public.players;
create policy players_select_mister_or_same_team_player
on public.players for select
to authenticated
using (
  public.is_team_owner(team_id)
  or team_id = public.current_player_team_id()
);

