create or replace function public.touch_chat_on_new_message()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.chats
  set updated_at = coalesce(new.created_at, now())
  where id = new.chat_id;

  return new;
end;
$$;

drop trigger if exists trg_touch_chat_on_new_message on public.messages;
create trigger trg_touch_chat_on_new_message
after insert on public.messages
for each row
execute function public.touch_chat_on_new_message();

