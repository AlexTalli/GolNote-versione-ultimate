-- -------------------------
-- PROFILI APP (mister/player)
-- -------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null check (role in ('mister', 'player')),
  nickname text not null unique,
  display_nickname text,
  player_id bigint,
  created_at timestamptz not null default now()
);

alter table public.profiles
  add column if not exists display_nickname text;

-- -------------------------
-- TEAMS
-- -------------------------
create table if not exists public.teams (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  color text not null,
  owner_user_id uuid not null references public.profiles(id) on delete cascade,
  password_hash text,
  created_at timestamptz not null default now(),
  unique (owner_user_id, name)
);

-- -------------------------
-- PLAYERS
-- -------------------------
create table if not exists public.players (
  id bigint generated by default as identity primary key,
  name text not null,
  number text not null,
  position text not null,
  team_id bigint references public.teams(id) on delete set null,
  created_at timestamptz not null default now()
);

-- profili.player_id -> players.id
alter table public.profiles
  drop constraint if exists profiles_player_id_fkey;

alter table public.profiles
  add constraint profiles_player_id_fkey
  foreign key (player_id) references public.players(id) on delete set null;

-- -------------------------
-- FINES
-- -------------------------
create table if not exists public.fines (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  type text not null,
  amount numeric(10,2) not null,
  description text,
  due_date date not null,
  is_paid boolean not null default false,
  paid_at timestamptz,
  notification_id text,
  created_at timestamptz not null default now()
);

-- -------------------------
-- TRAINING SESSIONS
-- -------------------------
create table if not exists public.training_sessions (
  id bigint generated by default as identity primary key,
  team_id bigint not null references public.teams(id) on delete cascade,
  session_date date not null,
  title text,
  note text,
  created_by uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

-- -------------------------
-- ATTENDANCE RECORDS
-- -------------------------
create table if not exists public.attendance_records (
  id bigint generated by default as identity primary key,
  session_id bigint not null references public.training_sessions(id) on delete cascade,
  player_id bigint not null references public.players(id) on delete cascade,
  status text not null check (status in (
    'present',
    'late',
    'absent_justified',
    'absent_unjustified',
    'injured'
  )),
  note text,
  updated_at timestamptz not null default now(),
  unique (session_id, player_id)
);

-- -------------------------
-- INDICI
-- -------------------------
create index if not exists idx_teams_owner on public.teams(owner_user_id);
create index if not exists idx_players_team on public.players(team_id);
create index if not exists idx_fines_player on public.fines(player_id);
create index if not exists idx_fines_due on public.fines(is_paid, due_date);
create index if not exists idx_sessions_team_date on public.training_sessions(team_id, session_date desc);
create index if not exists idx_attendance_session on public.attendance_records(session_id);
create index if not exists idx_attendance_player on public.attendance_records(player_id);

-- =========================
-- HELPER FUNCTIONS (RLS)
-- =========================
create or replace function public.current_player_id()
returns bigint
language sql
stable
security definer
set search_path = public, auth
as $$
  select p.player_id
  from public.profiles p
  where p.id = auth.uid()
$$;

create or replace function public.current_player_team_id()
returns bigint
language sql
stable
security definer
set search_path = public, auth
as $$
  select pl.team_id
  from public.players pl
  where pl.id = public.current_player_id()
$$;

create or replace function public.is_team_owner(team bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from public.teams t
    where t.id = team
      and t.owner_user_id = auth.uid()
  )
$$;

