create or replace function public.is_team_owner(team bigint)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (
    select 1
    from public.teams t
    where t.id = team
      and t.owner_user_id = auth.uid()
    union all
    select 1
    from public.team_misters tm
    where tm.team_id = team
      and tm.user_id = auth.uid()
  )
$$;

drop function if exists public.join_team_as_mister(bigint, text);

create function public.join_team_as_mister(p_team_id bigint, p_password text)
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if exists (
    select 1
    from public.teams t
    where t.id = p_team_id
      and t.mister_password is not null
      and t.mister_password = p_password
  ) then
    insert into public.team_misters (team_id, user_id)
    values (p_team_id, auth.uid())
    on conflict (team_id, user_id) do nothing;

    return true;
  end if;

  return false;
end;
$$;

revoke all on function public.join_team_as_mister(bigint, text) from public;
grant execute on function public.join_team_as_mister(bigint, text) to authenticated;

drop function if exists public.get_chat_sender_labels(bigint);

create function public.get_chat_sender_labels(p_chat_id bigint)
returns table (
  sender_id uuid,
  sender_label text
)
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  v_team_id bigint;
  v_player_id bigint;
begin
  select c.team_id, c.player_id
  into v_team_id, v_player_id
  from public.chats c
  where c.id = p_chat_id;

  if v_team_id is null or v_player_id is null then
    return;
  end if;

  -- 1) mister proprietario
  return query
  select
    t.owner_user_id::uuid as sender_id,
    coalesce(nullif(trim(tcn.nickname), ''), '1° Mister') as sender_label
  from public.teams t
  left join public.team_chat_nicknames tcn
    on tcn.team_id = t.id
   and tcn.user_id = t.owner_user_id
  where t.id = v_team_id;

  -- 2) mister delegati, in ordine di ingresso
  return query
  with ordered_misters as (
    select
      tm.user_id,
      row_number() over (order by tm.created_at asc) + 1 as mister_index
    from public.team_misters tm
    where tm.team_id = v_team_id
  )
  select
    om.user_id::uuid as sender_id,
    coalesce(nullif(trim(tcn.nickname), ''), (om.mister_index::text || '° Mister')) as sender_label
  from ordered_misters om
  left join public.team_chat_nicknames tcn
    on tcn.team_id = v_team_id
   and tcn.user_id = om.user_id;

  -- 3) giocatore della chat
  return query
  select
    pr.id::uuid as sender_id,
    'Giocatore' as sender_label
  from public.players pl
  left join public.profiles pr on pr.player_id = pl.id
  where pl.id = v_player_id;
end;
$$;

revoke all on function public.get_chat_sender_labels(bigint) from public;
grant execute on function public.get_chat_sender_labels(bigint) to authenticated;

drop function if exists public.get_joinable_team_players(bigint);

create function public.get_joinable_team_players(p_team_id bigint)
returns table (
  id bigint,
  name text,
  surname text,
  number text,
  "position" text,
  team_id bigint,
  team_name text,
  team_color text,
  created_at timestamptz,
  is_taken bigint,
  active_fines bigint,
  total_unpaid numeric
)
language sql
stable
security definer
set search_path = public, auth
as $$
  select
    p.id,
    p.name,
    p.surname,
    p.number,
    p.position,
    p.team_id,
    t.name as team_name,
    t.color as team_color,
    p.created_at,
    case
      when exists (select 1 from public.profiles pr where pr.player_id = p.id) then 1::bigint
      else 0::bigint
    end as is_taken,
    (
      select count(*)::bigint
      from public.fines f
      where f.player_id = p.id
        and f.is_paid = false
    ) as active_fines,
    (
      select coalesce(sum(f.amount), 0)
      from public.fines f
      where f.player_id = p.id
        and f.is_paid = false
    ) as total_unpaid
  from public.players p
  left join public.teams t on t.id = p.team_id
  where p.team_id = p_team_id
  order by
    coalesce(nullif(lower(trim(p.surname)), ''), lower(trim(p.name))),
    lower(trim(p.name));
$$;

create or replace function public.delete_my_account()
returns boolean
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  delete from auth.users where id = auth.uid();
  return true;
exception
  when others then
    return false;
end;
$$;

